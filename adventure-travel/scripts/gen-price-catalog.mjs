// Generates api/_lib/catalog.js from src/data/treks.ts so the order API prices bookings
// from the same numbers the site displays, without trusting anything the browser sends.
// Re-run after editing trek prices:  npm run catalog
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "src/data/treks.ts"), "utf8");

const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
});
const mod = { exports: {} };
new Function("module", "exports", outputText)(mod, mod.exports);

const catalog = {};
for (const trek of mod.exports.treks ?? []) {
  if (!trek.slug || !Number.isInteger(trek.price) || trek.price <= 0) {
    throw new Error(`Trek "${trek.name}" has no valid integer price.`);
  }
  catalog[trek.slug] = { name: trek.name, price: trek.price };
}
if (Object.keys(catalog).length === 0) throw new Error("No treks found in src/data/treks.ts");

const out = [
  "// AUTO-GENERATED by scripts/gen-price-catalog.mjs from src/data/treks.ts — do not edit.",
  "// Prices are INR per person.",
  `module.exports = ${JSON.stringify(catalog, null, 2)};`,
  "",
].join("\n");
fs.mkdirSync(path.join(root, "api/_lib"), { recursive: true });
fs.writeFileSync(path.join(root, "api/_lib/catalog.js"), out);
console.log(`Wrote api/_lib/catalog.js (${Object.keys(catalog).length} treks)`);
