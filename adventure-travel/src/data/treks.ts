export interface ItineraryDay {
  day: number;
  title: string;
  altitude: number;
  hours: number;
  description: string;
  meals?: string;
  /** Optional route/weather contingency note rendered as a bold callout. */
  note?: string;
}

export interface Trek {
  id: number;
  name: string;
  slug: string;
  region: string;
  country: string;
  location?: string;
  difficulty: "Easy" | "Moderate" | "Challenging" | "Strenuous";
  price: number;
  currency: string;
  rating?: number;
  reviewCount?: number;
  blurb: string;
  bestSeason: string;
  days: number;
  maxAltitude: number;
  elevationProfile: number[];
  itinerary: ItineraryDay[];
  /** Omit until real photos exist; pages show a branded "no photo" panel instead. */
  image?: string;
  featured?: boolean;
  groupSize?: number;
  /** ILP-restricted India–Tibet frontier zone offered as a permit-facilitated tour (not an open trek). */
  permitTour?: boolean;
  /**
   * Per-person price by room sharing, cheapest first; `price` must equal the first tier
   * (the "from" price). The order API charges the tier stored on the booking.
   */
  roomSharing?: { label: string; perRoom: number; price: number }[];
  /** Where the group sleeps, when it isn't the default twin-sharing tents. */
  stay?: { label: string; detail: string };
  /**
   * Town the package picks up from and returns to, when that isn't the trailhead town.
   * The price covers this town and back, shown Indiahikes-style as "Joshimath to Joshimath".
   */
  startsFrom?: string;
}

/** What the price covers, e.g. "Joshimath to Joshimath"; undefined when the trek has no pickup town. */
export function priceRoute(trek: Trek): string | undefined {
  return trek.startsFrom && `${trek.startsFrom} to ${trek.startsFrom}`;
}

/** Per-person price for a booked room tier; the base price when no tier was chosen, undefined for an unknown tier. */
export function pricePerPerson(trek: Trek, roomSharing?: string | null): number | undefined {
  if (!roomSharing) return trek.price;
  return trek.roomSharing?.find((r) => r.label === roomSharing)?.price;
}

export function slugify(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

